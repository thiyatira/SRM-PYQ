/** Flat list of all subjects (with their semester) for search / lookups. */
export const ALL_SUBJECTS: SubjectEntry[] = SEMESTERS.flatMap((sem) =>
  sem.subjects.map((sub) => ({ ...sub, semester: sem }))
);

const BY_CODE = new Map(ALL_SUBJECTS.map((s) => [s.code, s]));

export function getSubject(code: string | null | undefined): SubjectEntry | undefined {
  return code ? BY_CODE.get(code) : undefined;
}

export function getSemester(id: number | null | undefined): SemesterInfo | undefined {
  return SEMESTERS.find((s) => s.id === id);
}
