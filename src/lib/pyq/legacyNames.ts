/** Translates a question id `<paper>~<index>` from an old paper name to the current one (no-op otherwise). */
export function migrateQuestionId(code: string, id: string): string {
  const cut = id.lastIndexOf("~");
  if (cut < 0) return id;
  const renamed = LEGACY_PAPER_NAMES[`${code}/${id.slice(0, cut)}`];
  return renamed ? `${renamed}${id.slice(cut)}` : id;
}

/** Translates a stored bookmark key `<courseCode>|<paper>~<index>`. */
export function migrateBookmarkKey(key: string): string {
  const bar = key.indexOf("|");
  return bar < 0 ? key : `${key.slice(0, bar + 1)}${migrateQuestionId(key.slice(0, bar), key.slice(bar + 1))}`;
}
