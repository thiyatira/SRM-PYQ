/*
 * Text -> safe HTML pipeline for question/answer bodies.
 *
 * Safety model: question data is untrusted. Every piece of raw text is
 * HTML-escaped; only HTML produced by KaTeX (trust: false) and Prism (which
 * escapes its input) or generated by this file is ever emitted unescaped.
 * Such trusted fragments travel through the pipeline as private-use
 * placeholders and are substituted back at the very end.
 */

/* ── Code detection (heuristics for un-fenced code in the datasets) ───── */

function detectCodeLanguage(code: string): string {
  if (
    /System\.out\.|public\s+class\b|String\[\]\s+args|extends\s+\w+|implements\s+\w+|JFrame|JButton|Frame\b/.test(
      code
    )
  ) {
    return "java";
  }
  if (/cout\s*<<|cin\s*>>|std::|#include\s*<iostream>/.test(code)) {
    return "cpp";
  }
  if (/#include\b|printf\s*\(|scanf\s*\(|malloc\s*\(|strlen\s*\(|strcpy\s*\(/.test(code)) {
    return "c";
  }
  if (
    /(?:def\s+\w+\s*\(|import\s+(?:numpy|pandas|math|sys|os)|print\s*\()/.test(code) &&
    !code.includes(";")
  ) {
    return "python";
  }
  if (/\b(?:SELECT|CREATE\s+TABLE|INSERT\s+INTO|DROP\s+TABLE)\b/i.test(code)) {
    return "sql";
  }
  if (code.includes(";") && (code.includes("{") || /int\s+|double\s+/.test(code))) {
    if (code.includes("boolean") || code.includes("String")) {
      return "java";
    }
    return "c";
  }
  return "text";
}

const STRONG_CODE_STARTERS = [
  /^\s*#(?:include|define)\b/,
  /^\s*(?:public|private|protected)?\s*(?:static\s+)?(?:final\s+|abstract\s+)?(?:class|interface|enum)\s+\w+/,
  /^\s*import\s+[\w.*]+;/,
  /^\s*(?:import\s+(?:numpy|pandas|math|sys|os|re|random)\b|from\s+\w+\s+import\b)/,
  /^\s*def\s+\w+\s*\(/,
  /^\s*(?:public\s+)?(?:static\s+)?(?:void|int)\s+main\s*\(/,
  /^\s*System\.out\./,
  /^\s*(?:printf|scanf)\s*\(/,
  /^\s*(?:cout\s*<<|cin\s*>>)/,
  /^\s*(?:SELECT\s+.*FROM|CREATE\s+TABLE)\b/i,
];

const CODE_LINE_SIGNALS = [
  /[{};]\s*$/,
  /^\s*\/\//,
  /^\s*\/\*/,
  /^\s*\*\//,
  /^\s*System\.out\./,
  /^\s*(?:printf|scanf)\(/,
  /^\s*cout\s*<</,
  /^\s*cin\s*>>/,
  /^\s*(?:return|break|continue)\b.*[;:]$/,
  /^\s*(?:public|private|protected)\b/,
  /^\s*(?:int|float|double|char|boolean|String|long|short|void)\b.*[;=()]$/,
  /^\s*(?:if|else\s+if|else|for|while|do|switch)\s*\(.*[:{;]?$/,
  /^\s*case\s+[^:]+:|^\s*default\s*:/,
  /^\s*def\s+\w+/,
  /^\s*class\s+\w+/,
  /^\s*#include\b/,
  /^\s*throw\s+new\b/,
  /^\s*[a-zA-Z_]\w*\s*=\s*.+;/,
  /^\s*[a-zA-Z_]\w*\.[a-zA-Z_]\w*\(.*;$/,
  /^\s*[{}]$/,
];

const MCQ_OPTION_RE = /^\s*(?:[-*]\s*)?(?:[A-Da-d]\.|\([A-Da-d]\)|[A-Da-d]\)|[A-Da-d]:)\s+/;

function isMcqOption(line: string): boolean {
  return MCQ_OPTION_RE.test(line.trim());
}

function isProseQuestionEnd(line: string): boolean {
  const s = line.trim();
  if (!s || s.endsWith(";") || s.endsWith("{") || s.endsWith("}")) return false;
  const lower = s.toLowerCase();
  if (lower.endsWith("?")) return true;
  return (
    /^(?:why|what|how|which|explain|predict|find|determine|calculate|debug|state)\b/i.test(
      lower
    ) &&
    (s.includes(":") || s.includes("?") || s.includes("."))
  );
}

function isCodeLine(line: string): boolean {
  const s = line.trim();
  if (!s || isMcqOption(line) || isProseQuestionEnd(line)) return false;
  return CODE_LINE_SIGNALS.some((pat) => pat.test(line));
}

function autoFenceCode(text: string): string {
  if (!text || text.includes("```")) return text;

  const lines = text.split("\n");
  const n = lines.length;
  const resultLines: string[] = [];
  let i = 0;

  while (i < n) {
    const line = lines[i];
    const isStart =
      STRONG_CODE_STARTERS.some((pat) => pat.test(line)) ||
      (isCodeLine(line) && i + 1 < n && isCodeLine(lines[i + 1]));

    if (isStart) {
      const block: string[] = [];
      const startIndex = i;
      while (i < n) {
        const curr = lines[i];
        if (!curr.trim()) {
          if (i + 1 < n && isCodeLine(lines[i + 1])) {
            block.push(curr);
            i++;
            continue;
          } else {
            break;
          }
        }
        if (isMcqOption(curr) || isProseQuestionEnd(curr)) break;
        if (isCodeLine(curr)) {
          block.push(curr);
          i++;
        } else {
          break;
        }
      }

      if (i === startIndex) {
        resultLines.push(lines[i]);
        i++;
        continue;
      }

      const codeStr = block.join("\n").trim();
      const hasStrong = STRONG_CODE_STARTERS.some((pat) => pat.test(codeStr));
      const hasSyntax = /[;{}():#]/.test(codeStr);

      if ((block.length >= 2 || hasStrong) && hasSyntax) {
        const lang = detectCodeLanguage(codeStr);
        const nonBlank = block.filter((l) => l.trim().length > 0);
        const minIndent =
          nonBlank.length > 0
            ? Math.min(...nonBlank.map((l) => l.search(/\S|$/)))
            : 0;
        const normalized = block
          .map((l) =>
            l.trim().length > 0 && minIndent > 0 ? l.slice(minIndent) : l
          )
          .join("\n")
          .trim();

        if (resultLines.length > 0 && resultLines[resultLines.length - 1].trim()) {
          resultLines.push("");
        }
        resultLines.push(`\`\`\`${lang}`);
        resultLines.push(normalized);
        resultLines.push("```");
        if (i < n && lines[i].trim()) {
          resultLines.push("");
        }
      } else {
        resultLines.push(...block);
      }
    } else {
      resultLines.push(line);
      i++;
    }
  }

  return resultLines.join("\n");
}

/* ── Escaping ─────────────────────────────────────────────────────────── */

export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/* ── Syntax highlighting ──────────────────────────────────────────────── */

const LANG_ALIASES: Record<string, string> = {
  js: "javascript",
  py: "python",
  "c++": "cpp",
  sh: "bash",
  shell: "bash",
  zsh: "bash",
  mysql: "sql",
};

function highlight(code: string, lang: string): string {
  const grammar = Object.prototype.hasOwnProperty.call(Prism.languages, lang)
    ? Prism.languages[lang]
    : undefined;
  if (!grammar || typeof grammar !== "object") return escapeHtml(code);
  try {
    return Prism.highlight(code, grammar, lang);
  } catch {
    return escapeHtml(code);
  }
}

function codeBlockHtml(rawCode: string, rawLang: string): string {
  let lang = (rawLang || detectCodeLanguage(rawCode) || "text").trim().toLowerCase();
  lang = LANG_ALIASES[lang] ?? lang;
  const label = escapeHtml(lang.toUpperCase());
  const highlighted = highlight(rawCode, lang);

  return `<div class="code-block-wrapper my-3.5 rounded-xl overflow-hidden border border-gray-200 dark:border-neutral-700/80 bg-gray-50/90 dark:bg-neutral-900 shadow-sm not-prose text-left">
  <div class="code-block-header flex items-center justify-between px-3.5 py-1.5 bg-gray-100 dark:bg-neutral-800/90 border-b border-gray-200 dark:border-neutral-700/80 text-xs text-gray-600 dark:text-gray-300 select-none">
    <div class="flex items-center gap-1.5">
      <span class="inline-flex gap-1" aria-hidden="true">
        <span class="w-2.5 h-2.5 rounded-full bg-red-400/80 dark:bg-red-500/70"></span>
        <span class="w-2.5 h-2.5 rounded-full bg-yellow-400/80 dark:bg-yellow-500/70"></span>
        <span class="w-2.5 h-2.5 rounded-full bg-green-400/80 dark:bg-green-500/70"></span>
      </span>
      <span class="font-mono uppercase font-semibold text-[11px] tracking-wider text-gray-600 dark:text-gray-300 ml-1.5">${label}</span>
    </div>
    <button type="button" class="copy-code-btn inline-flex items-center gap-1 text-[11px] font-medium text-gray-600 dark:text-gray-300 hover:text-blue-700 dark:hover:text-blue-300 px-2 py-0.5 rounded hover:bg-gray-200 dark:hover:bg-neutral-700 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 transition" aria-label="Copy code to clipboard">
      <svg class="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M8 16H6a2 2 0 01-2-2V6a2 2 0 012-2h8a2 2 0 012 2v2m-6 12h8a2 2 0 002-2v-8a2 2 0 00-2-2h-8a2 2 0 00-2 2v8a2 2 0 002 2z"></path></svg>
      <span>Copy</span>
    </button>
  </div>
  <pre class="overflow-x-auto p-4 font-mono text-[13px] leading-relaxed text-gray-800 dark:text-gray-200" tabindex="0"><code class="language-${escapeHtml(lang)}">${highlighted}</code></pre>
</div>`;
}

/* ── KaTeX ────────────────────────────────────────────────────────────── */

function renderMath(tex: string, displayMode: boolean): string {
  try {
    return katex.renderToString(tex.trim(), { displayMode, throwOnError: false });
  } catch {
    const d = displayMode ? "$$" : "$";
    return `<span>${escapeHtml(d + tex + d)}</span>`;
  }
}

/* ── Markdown-ish -> HTML ─────────────────────────────────────────────── */

// Private-use characters delimit placeholders for already-safe HTML fragments.
const PH_OPEN = "\uE000";
const PH_CLOSE = "\uE001";
const PH_BLOCK_OPEN = "\uE002"; // placeholders for block-level fragments (no <br> around them)
const PH_STRIP_RE = /[\uE000-\uE002]/g;
const PH_RE = /[\uE000\uE002](\d+)\uE001/g;
const PH_ONLY_RE = /^\uE002\d+\uE001$/;

const LIST_ITEM_RE = /^\s*[-•]\s+(.*)$/;
const INLINE_CODE_CLASS =
  "px-1.5 py-0.5 rounded bg-gray-100 dark:bg-neutral-700/80 text-pink-700 dark:text-pink-300 font-mono text-xs sm:text-sm font-medium border border-gray-200/60 dark:border-neutral-600/60";

function inlineFormat(escaped: string): string {
  return escaped
    .replace(/\*\*([^*\n]+)\*\*/g, "<strong>$1</strong>")
    .replace(/\*([^\s*](?:[^*\n]*?[^\s*])?)\*/g, "<em>$1</em>")
    .replace(
      /\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)\)/g,
      '<a href="$2" target="_blank" rel="noopener noreferrer" class="text-blue-700 dark:text-blue-300 underline">$1</a>'
    );
}

function convert(rawMd: string): string {
  const store: string[] = [];
  const hold = (html: string, block = false) => {
    store.push(html);
    return `${block ? PH_BLOCK_OPEN : PH_OPEN}${store.length - 1}${PH_CLOSE}`;
  };

  let text = autoFenceCode(rawMd.replace(PH_STRIP_RE, "").replace(/\r\n?/g, "\n"));

  // 1. fenced code blocks
  text = text.replace(
    /```([a-zA-Z0-9_+#.-]*)[ \t]*\n?([\s\S]*?)```/g,
    (_, lang: string, code: string) => hold(codeBlockHtml((code || "").trim(), lang), true)
  );
  // 2. inline code
  text = text.replace(/`([^`\n]+)`/g, (_, code: string) =>
    hold(`<code class="${INLINE_CODE_CLASS}">${escapeHtml(code)}</code>`)
  );
  // 3. math ($$..$$ first, then $..$; inline math may not start/end with a space,
  //    so prices like "$5 and $10" are left alone)
  text = text
    .replace(/\$\$([\s\S]+?)\$\$/g, (_, tex: string) => hold(renderMath(tex, true), true))
    .replace(/\$([^\s$](?:[^$\n]*?[^\s$])?)\$/g, (_, tex: string) =>
      hold(renderMath(tex, false))
    );

  // 4. everything left is plain text: escape it, then apply light markdown
  const lines = escapeHtml(text).split("\n");
  const pieces: { html: string; block: boolean }[] = [];
  for (let i = 0; i < lines.length; ) {
    if (LIST_ITEM_RE.test(lines[i])) {
      const items: string[] = [];
      while (i < lines.length && LIST_ITEM_RE.test(lines[i])) {
        items.push(`<li>${inlineFormat(lines[i].replace(LIST_ITEM_RE, "$1"))}</li>`);
        i++;
      }
      pieces.push({ html: `<ul class="list-disc pl-6 my-1">${items.join("")}</ul>`, block: true });
    } else {
      const line = lines[i++];
      pieces.push({ html: inlineFormat(line), block: PH_ONLY_RE.test(line.trim()) });
    }
  }
  let html = "";
  pieces.forEach((p, idx) => {
    if (idx > 0 && !p.block && !pieces[idx - 1].block) html += "<br>";
    html += p.html;
  });

  // 5. put the trusted fragments back
  return html.replace(PH_RE, (_, n: string) => store[Number(n)] ?? "");
}

const CACHE_LIMIT = 600;
const cache = new Map<string, string>();

/** Convert question/answer markdown (with code fences and LaTeX) to sanitised HTML. Memoised. */
export function markdownToHtml(rawMd?: string | null): string {
  if (!rawMd) return "";
  const hit = cache.get(rawMd);
  if (hit !== undefined) {
    cache.delete(rawMd); // refresh LRU position
    cache.set(rawMd, hit);
    return hit;
  }
  const out = convert(rawMd);
  cache.set(rawMd, out);
  if (cache.size > CACHE_LIMIT) {
    const oldest = cache.keys().next().value;
    if (oldest !== undefined) cache.delete(oldest);
  }
  return out;
}
